function renderHelpView() {
  const el = document.getElementById("helpView");
  if (!el) return;
  const isOwner = typeof Auth !== "undefined" && Auth.isOwner && Auth.isOwner();
  const allowed = (t) => typeof tabAllowed !== "function" || tabAllowed(t);
  const secs = HELP_SECTIONS.filter(s => allowed(s.tab) && !(s.ownerOnly && !isOwner) && !(s.staffOnly && isOwner));
  const day = [
    ["☀️", "الصبح", "استلام الطلبية + جولة التوثيق الأولى"],
    ["🕛", "الظهر", "جولة التوثيق الثانية"],
    ["🌙", "آخر الدوام", "جولة الإغلاق + جرد المتبقي + الهدر + إغلاق العهدة"]
  ];
  el.innerHTML = `
    <div class="help-head">
      <h2>📘 طريقة الاستخدام</h2>
      <p>شرح كل شاشة وكل زر تستخدمه، خطوة بخطوة.</p>
    </div>
    <div class="help-day">
      <div class="help-day-title">يوم الفرع باختصار</div>
      ${day.map(([i, t, d]) => `<div class="help-day-row"><span class="help-day-ic">${i}</span><b>${t}</b><span>${d}</span></div>`).join("")}
    </div>
    <nav class="help-toc" aria-label="المحتويات">${secs.map((s, i) => `<a href="#help-${i}" data-help="${i}">${s.icon} ${s.title}</a>`).join("")}</nav>
    ${secs.map((s, i) => `
      <section class="help-sec" id="help-${i}">
        <h3><span class="help-num">${i + 1}</span><span>${s.icon} ${s.title}</span></h3>
        <div class="help-body">
          <ol>${s.steps.map(t => `<li>${t}</li>`).join("")}</ol>
          <img class="help-shot" src="assets/guide/${s.img}.jpg" alt="${s.title}" loading="lazy" width="390" height="780">
        </div>
      </section>`).join("")}
    <section class="help-sec help-tips">
      <h3><span>💡 نصائح</span></h3>
      <ul>${HELP_TIPS.map(t => `<li>${t}</li>`).join("")}</ul>
    </section>`;
  el.querySelectorAll(".help-toc a").forEach(a => a.addEventListener("click", (e) => {
    e.preventDefault();
    const t = document.getElementById("help-" + a.dataset.help);
    if (t) t.scrollIntoView({ behavior: "smooth", block: "start" });
  }));
}
